QSet<char32_t> initCharSet(const char *utf8Str)
{
    QSet<char32_t> set;
    const QString str = QString::fromUtf8(utf8Str);
    set.reserve(str.size());
    for (qsizetype i = 0; i < str.size(); ++i) {
        if (str.at(i).isHighSurrogate() && (i + 1) < str.size() && str.at(i + 1).isLowSurrogate()) {
            set.insert(QChar::surrogateToUcs4(str.at(i), str.at(i + 1)));
            ++i;
        } else {
            set.insert(str.at(i).unicode());
        }
    }
    return set;
}

